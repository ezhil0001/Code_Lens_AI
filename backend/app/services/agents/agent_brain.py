    async def _generate_response(self, prompt: str) -> tuple[str, int]:
        """Generate response from LLM.
        
        Supports multiple LLM backends via LangChain:
        - ChatOllama (local Llama 3.1 via Ollama)
        - ChatGroq (cloud Groq API)
        - ChatOpenAI (OpenAI GPT models)
        
        Falls back to mock if LLM not available.
        
        LLM Client Interface (required methods):
        - async generate(prompt, temperature, max_tokens, timeout) -> dict
          Returns: {"content": str, "tokens": int}
        - async stream(prompt, temperature, max_tokens) -> AsyncIterator[str]
          Yields: text chunks
        """
        try:
            if not self.llm_client:
                logger.warning("LLM client not configured, using mock response")
                return self._mock_response(prompt)
            
            log_step(
                "[LLM_START]",
                f"non-streaming  model={getattr(self.config, 'llm_model', '?')}  "
                f"temp={self.config.llm_temperature}  max_tokens={self.config.llm_max_tokens}"
            )
            with timed("[LLM_START]") as ll_ctx:
                # Call actual LLM via client
                response = await self.llm_client.generate(
                    prompt=prompt,
                    temperature=self.config.llm_temperature,
                    max_tokens=self.config.llm_max_tokens,
                    timeout=self.config.llm_timeout_seconds,
                )

                if isinstance(response, dict):
                    content, tokens = response.get("content", ""), response.get("tokens", 0)
                else:
                    # Direct string response
                    content, tokens = str(response), len(str(response).split()) // 4
                ll_ctx["tokens"] = tokens
                ll_ctx["chars"] = len(content)
            return content, tokens
        
        except Exception as e:
            flow_logger.bind(tag="[LLM_START]").error(f"FAILED: {e}")
            logger.error(f"Error generating response: {e}")
            return self._mock_response(prompt)
    
